#!/usr/bin/env node
// Markdown is the only instruction source; runtime reads individual capabilities.
import {readFileSync, writeFileSync} from 'node:fs'
import {fileURLToPath} from 'node:url'
import {resolve, dirname} from 'node:path'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const source = resolve(root, 'packages/editor/ai-skills/document-design')
const target = resolve(root, 'packages/blockcraft-agent/src/core/document-design-skills.generated.ts')
const prefix = 'blockcraft.skill.document-design'
const entries = [
  ['SKILL.md', '', '文档设计', '设计或美化可编辑文档：先选择风格与布局，再按需读取对象、文字、视觉和执行指南。'],
  ['references/layout-and-objects.md', '.layout', '文档布局与对象', '按内容增长、改宽和共同几何需求选择文档流、分栏、文本框、形状或组合。'],
  ['references/text-and-paragraphs.md', '.typography', '文字与段落样式', '区分文档、段落、行内和对象文字样式；处理层次、间距、装饰线与填写提示。'],
  ['references/visual-recipes.md', '.visual', 'HTML 设计与原生映射', '先做带能力标注的 HTML，以共同设计参数映射原生文档，再对照修正；包含视觉风格配方。'],
  ['references/apply-and-check.md', '.execution', '文档设计执行与验证', '在本次宿主能力内实施设计，保护既有内容并按布局验证编辑、增长与保存。'],
]
const paths = new Map(entries.map(([path, suffix]) => [path, prefix + suffix]))
const capabilities = entries.map(([path, suffix, title, description]) => {
  const markdown = readFileSync(resolve(source, path), 'utf8')
  const instructions = markdown.replace(/^---\n[\s\S]*?\n---\n/, '').trim()
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, (_, label, link) => {
      const id = paths.get(link)
      if (!id) throw new Error(`Unmapped skill reference: ${path} -> ${link}`)
      return `${label}（用 blockcraft.get_capability 读取 ${id}）`
    })
  return {id: prefix + suffix, kind: 'skill', title, description,
    domains: ['document', 'design'],
    ...(suffix ? {} : {capabilityIds: entries.slice(1).map(entry => prefix + entry[1])}),
    instructions}
})
const output = `// Generated by scripts/sync-document-design-skill.mjs. Do not edit.\nimport type {DocumentAgentSkillCapability} from './host-extension'\n\nexport const BLOCKCRAFT_DOCUMENT_DESIGN_SKILLS: readonly DocumentAgentSkillCapability[] = ${JSON.stringify(capabilities, null, 2)}\n`
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Document design skill drift: run node scripts/sync-document-design-skill.mjs')
  console.log(`Document design skill: ${capabilities.length} capabilities match Markdown sources.`)
} else {
  writeFileSync(target, output)
  console.log(`Generated ${target}`)
}
